"""Manual OpenSSL oracle generation; never used by the C test runner.

All private keys are PUBLIC TEST VALUES (integers 1..4). Work files go only to
build/m07e-oracle. Requires OpenSSL on PATH or OPENSSL environment variable.
Certificates use generation-time dates; the emitted test clock derives from
OpenSSL's reported leaf notBefore, never the C host's wall clock.
"""
import datetime
import os
from pathlib import Path
import subprocess

repo = Path(__file__).resolve().parents[3]
work = repo / "build/m07e-oracle"
work.mkdir(parents=True, exist_ok=True)
openssl = os.environ.get("OPENSSL", "openssl")
(work / "openssl.cnf").write_text("[req]\ndistinguished_name=dn\n[dn]\n")


def run(*args):
    return subprocess.check_output([openssl, *args], cwd=work, stderr=subprocess.PIPE,
                                   env={**os.environ, "OPENSSL_CONF": str(work / "openssl.cnf")})


def cert(name, issuer, serial, ca=False):
    (work / "extensions.cnf").write_text(
        "basicConstraints=critical,CA:" + ("TRUE,pathlen:0" if ca else "FALSE")
        + "\nkeyUsage=critical," + ("keyCertSign,cRLSign" if ca else "digitalSignature")
        + "\nsubjectKeyIdentifier=hash\nauthorityKeyIdentifier=keyid,issuer\n")
    run("req", "-new", "-key", name + ".pem", "-subj", "/CN=" + name, "-out", name + ".csr")
    run("x509", "-req", "-in", name + ".csr", "-CA", issuer + ".crt", "-CAkey", issuer + ".pem",
        "-set_serial", str(serial), "-days", "1000", "-sha256", "-extfile", "extensions.cnf", "-out", name + ".crt")


for index, name in enumerate(("root", "intermediate", "leaf", "other"), 1):
    # SEC1 ECPrivateKey containing version, fixed scalar and named-curve OID.
    key = bytes.fromhex("30310201010420") + index.to_bytes(32, "big") + bytes.fromhex("a00a06082a8648ce3d030107")
    (work / (name + ".der")).write_bytes(key)
    run("ec", "-inform", "DER", "-in", name + ".der", "-out", name + ".pem")
for name in ("root", "other"):
    run("req", "-new", "-x509", "-key", name + ".pem", "-subj", "/CN=" + name, "-sha256", "-days", "2000",
        "-addext", "basicConstraints=critical,CA:TRUE,pathlen:1", "-addext", "keyUsage=critical,keyCertSign,cRLSign", "-out", name + ".crt")
cert("intermediate", "root", 2, True)
cert("leaf", "intermediate", 3)
run("verify", "-CAfile", "root.crt", "-untrusted", "intermediate.crt", "leaf.crt")
message = b"Matter C independent OpenSSL vector"
(work / "message.bin").write_bytes(message)
signature = run("dgst", "-sha256", "-sign", "leaf.pem", "message.bin")
# OpenSSL's ECDSA DER result consists of two short INTEGERs.
assert signature[0] == 0x30 and signature[1] == len(signature) - 2
position = 2
raw = b""
for _ in range(2):
    assert signature[position] == 2
    size = signature[position + 1]
    value = int.from_bytes(signature[position + 2: position + 2 + size], "big")
    raw += value.to_bytes(32, "big")
    position += 2 + size
assert position == len(signature)
run("pkey", "-in", "intermediate.pem", "-pubout", "-out", "peer.pem")
secret = run("pkeyutl", "-derive", "-inkey", "leaf.pem", "-peerkey", "peer.pem")
csr = run("req", "-new", "-key", "leaf.pem", "-subj", "/CN=Reference", "-sha256", "-outform", "DER")
(work / "reference.csr.der").write_bytes(csr)
run("req", "-inform", "DER", "-in", "reference.csr.der", "-verify", "-noout")
vectors = {"cred_message": message, "cred_signature": raw, "cred_secret": secret, "cred_csr": csr}
for name in ("root", "intermediate", "leaf", "other"):
    vectors["cred_" + name] = run("x509", "-in", name + ".crt", "-outform", "DER")
    if name in ("leaf", "intermediate"):
        pub = run("pkey", "-in", name + ".pem", "-pubout", "-outform", "DER")[-65:]
        assert len(pub) == 65 and pub[0] == 4
        vectors["cred_" + name + "_public"] = pub
saved_intermediate = (work / "intermediate.crt").read_bytes()
cert("intermediate", "root", 4, False)
vectors["cred_notca"] = run("x509", "-in", "intermediate.crt", "-outform", "DER")
(work / "intermediate.crt").write_bytes(saved_intermediate)
run("req", "-new", "-x509", "-key", "root.pem", "-subj", "/CN=root", "-sha256", "-days", "2000",
    "-addext", "basicConstraints=critical,CA:TRUE,pathlen:0", "-addext", "keyUsage=critical,keyCertSign,cRLSign", "-out", "root0.crt")
vectors["cred_root0"] = run("x509", "-in", "root0.crt", "-outform", "DER")
start = run("x509", "-in", "leaf.crt", "-startdate", "-noout").decode().strip().split("=", 1)[1]
now = datetime.datetime.strptime(start, "%b %d %H:%M:%S %Y %Z") + datetime.timedelta(days=1)
version = run("version").decode().strip()
text = "/* Generated by fixtures/generate_credentials.py; " + version + ".\n * Public test keys 1..4; never use as device credentials. */\n"
for name, data in vectors.items():
    text += "static const uint8_t " + name + "[] = {\n"
    for offset in range(0, len(data), 16):
        text += "    " + ",".join("0x%02x" % b for b in data[offset:offset + 16]) + ",\n"
    text += "};\n"
text += "static const Matter_Cert_Time_Policy_T cred_time = {MATTER_CERT_TIME_SUPPLIED,{%d,%d,%d,%d,%d,%d}};\n" % (
    now.year, now.month, now.day, now.hour, now.minute, now.second)
(repo / "tools/matter/tests/test_credentials_vectors.h").write_text(text)
print(version)
print("Generated DER chain/CSR, ECDSA and ECDH independent vectors; OpenSSL chain/CSR verification passed.")
