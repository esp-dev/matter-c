from pathlib import Path
import struct

ROOT = Path(__file__).resolve().parents[3]
TYPES = {'SIGNED': 0, 'UNSIGNED': 4, 'BOOL': 8, 'FLOAT32': 10, 'FLOAT64': 11,
         'UTF8': 12, 'BYTES': 16, 'NULL': 20, 'STRUCTURE': 21, 'ARRAY': 22,
         'LIST': 23, 'END': 24}


def token(kind, value=0, width=0, control=0, number=0, vendor=0, profile=0):
    return dict(kind=kind, value=value, width=width, control=control,
                number=number, vendor=vendor, profile=profile)


def encode(t):
    kind, value, width, control = (t[k] for k in ('kind', 'value', 'width', 'control'))
    wire = TYPES[kind]
    data = b''
    if kind in ('SIGNED', 'UNSIGNED', 'UTF8', 'BYTES'):
        assert width in (1, 2, 4, 8)
        wire += width.bit_length()-1
        data = (len(value).to_bytes(width, 'little') + value if kind in ('UTF8', 'BYTES')
                else value.to_bytes(width, 'little', signed=kind == 'SIGNED'))
    elif kind == 'BOOL':
        wire += value
    elif kind.startswith('FLOAT'):
        data = value.to_bytes(4 if kind == 'FLOAT32' else 8, 'little')
    tag = b''
    if control >= 6:
        tag += t['vendor'].to_bytes(2, 'little') + t['profile'].to_bytes(2, 'little')
    if control:
        tag += t['number'].to_bytes(1 if control == 1 else 4 if control in (3, 5, 7) else 2, 'little')
    return bytes([wire | control << 5]) + tag + data


def cbytes(data):
    return '"'+''.join(f'\\x{v:02x}' for v in data)+'"'


def main():
    cases = []
    def add(name, *tokens):
        cases.append((name, b''.join(encode(t) for t in tokens), tokens))
    for width in (1, 2, 4, 8):
        for kind, value in [('SIGNED', -29), ('SIGNED', 63), ('UNSIGNED', 91)]:
            add(f'{kind.lower()}-{width}-{value}', token(kind, value, width))
        for kind, value in [('UTF8', 'meter \u03a9'.encode()), ('BYTES', b'\xfe\0\x7a\x81')]:
            add(f'{kind.lower()}-length-{width}', token(kind, value, width))
    for kind in ('FLOAT32', 'FLOAT64'):
        fmt = '<f' if kind == 'FLOAT32' else '<d'
        for number, value in enumerate((0.0, 1.5, -2.25, float('inf'), -float('inf'), float('nan'))):
            add(f'{kind.lower()}-{number}', token(kind, int.from_bytes(struct.pack(fmt, value), 'little')))
    for value in (0, 1):
        add('bool-'+str(value), token('BOOL', value))
    add('null', token('NULL'))
    for kind in ('STRUCTURE', 'ARRAY', 'LIST'):
        add('empty-'+kind.lower(), token(kind), token('END'))
    add('record', token('STRUCTURE'), token('SIGNED', -29, 1, 1, 7),
        token('UTF8', b'phase-B', 1, 1, 9), token('END'))
    add('mixed-array', token('ARRAY'), token('SIGNED', 63, 1), token('SIGNED', -91003, 4),
        token('STRUCTURE'), token('END'), token('FLOAT32', 0xc0100000),
        token('UTF8', b'meter B', 1), token('END'))
    add('signed-array', token('ARRAY'), *(token('SIGNED', x, 1) for x in (9, -4, 31, 0)), token('END'))
    for control in range(8):
        number = 0 if not control else 23 if control == 1 else 0x12345678 if control in (3, 5, 7) else 0x1234
        add('tag-form-'+str(control), token('LIST'),
            token('UNSIGNED', 91, 1, control, number, 0xfff2 if control >= 6 else 0, 0x1357 if control >= 6 else 0), token('END'))
    add('qualified-record', token('STRUCTURE', control=6, number=23, vendor=0xfff2, profile=0x1357),
        token('UNSIGNED', 91, 1, 6, 41, 0xfff2, 0x1357), token('END'))
    text = ('/* SPDX-License-Identifier: Apache-2.0\n'
            ' * Generated by fixtures/generate_tlv_reference.py; synthetic schema matrix. */\n'
            'typedef struct { Matter_Tlv_Element_T element; uint8_t width; } Tlv_Reference_Token;\n'
            'typedef struct { const uint8_t* data; size_t size; const Tlv_Reference_Token* tokens; size_t count; } Tlv_Reference_Case;\n')
    for i, (_, data, tokens) in enumerate(cases):
        text += f'static const Tlv_Reference_Token tlv_tokens_{i}[]={{\n'
        for t in tokens:
            value, kind = t['value'], t['kind']
            fields = ['.type=MATTER_TLV_'+kind,
                      '.tag={'+','.join('.'+k+'='+str(t[k]) for k in ('control','number','vendor','profile'))+'}']
            if kind in ('UTF8','BYTES'):
                fields += ['.data=(const uint8_t*)'+cbytes(value), '.size='+str(len(value))]
            elif kind == 'SIGNED':
                fields += ['.signed_value='+str(value)]
            else:
                fields += [f'.unsigned_value=UINT64_C({value})']
            text += '    {{'+','.join(fields)+'},'+str(t['width'])+'},\n'
        text += '};\n'
    text += 'static const Tlv_Reference_Case tlv_reference[]={\n'
    for i, (name, data, tokens) in enumerate(cases):
        assert len(data) < 96
        text += f'    {{(const uint8_t*){cbytes(data)},{len(data)},tlv_tokens_{i},{len(tokens)}}}, /* {name} */\n'
    text += '};\n'
    (ROOT/'tools/matter/tests/test_tlv_reference.h').write_text(text, encoding='utf-8', newline='\n')
    # Preserve the project's existing malformed/boundary corpus unchanged.
    seeds = ROOT/'tools/matter/fuzz/seeds.txt'
    old = seeds.read_text(encoding='utf-8')
    boundary = old[old.index('duplicate|'):]
    seeds.write_text('# Synthetic TLV schema matrix; regenerate with fixtures/generate_tlv_reference.py.\n'
                     + ''.join(n+'|'+data.hex()+'\n' for n, data, _ in cases)
                     + '# Project-authored malformed/boundary cases.\n'+boundary, encoding='utf-8', newline='\n')
    # IM values are project choices; only field/type numbers come from schema.
    path = [token('UNSIGNED',0,1,1,2),token('UNSIGNED',0x28,1,1,3),token('UNSIGNED',2,1,1,4)]
    request = [token('STRUCTURE'),token('ARRAY',control=1,number=0),token('LIST'),*path,
               token('END'),token('END'),token('BOOL',1,control=1,number=3),token('UNSIGNED',13,1,1,255),token('END')]
    report = [token('STRUCTURE'),token('ARRAY',control=1,number=1),token('STRUCTURE'),token('STRUCTURE',control=1,number=1),
              token('UNSIGNED',7,1,1,0),token('LIST',control=1,number=1),*path,token('END'),token('UNSIGNED',0xfff1,2,1,2),
              token('END'),token('END'),token('END'),token('BOOL',1,control=1,number=4),token('UNSIGNED',13,1,1,255),token('END')]
    text = ('/* SPDX-License-Identifier: Apache-2.0\n * Generated independently from the IM schema by fixtures/generate_tlv_reference.py.\n'
            ' * Project fixture: endpoint 0, Basic Information/VendorID, VID fff1, version 7. */\n')
    for name, tokens in [('im_request',request),('im_report',report)]:
        text += 'static const uint8_t '+name+'[]={'+','.join(f'0x{b:02x}' for t in tokens for b in encode(t))+'};\n'
    (ROOT/'tools/matter/tests/test_im_vectors.h').write_text(text, encoding='utf-8', newline='\n')
    print(f'Generated {len(cases)} synthetic TLV cases, fuzz seeds and two IM fixtures')


if __name__ == '__main__':
    main()
