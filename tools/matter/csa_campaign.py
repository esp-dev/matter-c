"""Resume the frozen CSA campaign from public evidence; no lab writes or secrets."""
import argparse
import collections
import copy
import json
from pathlib import Path
import re


def campaign(root):
    folder = root / 'doc' / 'oss'
    plan = json.loads((folder / 'csa-campaign.json').read_bytes())
    rows = copy.deepcopy(plan['entries'])
    identity = lambda row: (row['case'], row['endpoint'], row['collection'])
    if len({identity(row) for row in rows}) != len(rows):
        raise ValueError('Duplicate checkpoint identity')
    counts = dict(collections.Counter(row['status'] for row in rows))
    counts['NA'] = plan['checkpoint_counts']['NA']
    if counts != plan['checkpoint_counts']:
        raise ValueError('Checkpoint counts differ from evidence')
    reports = sorted((int(match[1]), match[2], path) for path in folder.glob('csa*-results.json')
                     if (match := re.fullmatch(r'csa(\d+)([a-z]?)-results.json', path.name))
                     and (int(match[1]), match[2]) > (plan['checkpoint_stage'], ''))
    latest = folder / plan['checkpoint_evidence']
    for _, _, path in reports:
        report = json.loads(path.read_bytes())
        for change in report.get('classification_changes', []):
            found = [row for row in rows if row['case'] == change['case'] and
                     row['endpoint'] == change['endpoint'] and
                     ('collection' not in change or row['collection'] == change['collection'])]
            if len(found) != 1:
                raise ValueError(f'Ambiguous or absent campaign identity in {path.name}')
            row = found[0]
            if 'previous' in change and row['status'] != change['previous']:
                raise ValueError(f'Unexpected predecessor for {row["case"]}')
            row.update({key: change[key] for key in ('status', 'manual_result', 'run_id') if key in change})
            row['evidence'] = path.name
        counts = dict(collections.Counter(row['status'] for row in rows))
        counts['NA'] = plan['checkpoint_counts']['NA']
        if report.get('latest_counts', counts) != counts:
            raise ValueError(f'Count mismatch after {path.name}; review applicability/checkpoint')
        latest = path
    if any(row['status'] not in ('PASS', 'FAIL', 'MANUAL', 'BLOCKED') for row in rows):
        raise ValueError('Profile change requires a reviewed checkpoint, not a silent omission')
    if any(row.get('manual_result') not in (None, 'PASS', 'FAIL', 'BLOCKED') for row in rows):
        raise ValueError('Unknown manual verdict')
    if sum(counts.values()) != 862:
        raise ValueError('Unexpected frozen matrix size')
    return plan, rows, counts, latest.name


def render(plan, rows, counts, latest):
    waiting = [row for row in rows if row['status'] == 'BLOCKED' or
               row['status'] == 'MANUAL' and not row.get('manual_result')]
    failures = [row for row in rows if row['status'] == 'FAIL' or row.get('manual_result') == 'FAIL']
    manual = collections.Counter(row.get('manual_result', 'NOT_RUN') for row in rows if row['status'] == 'MANUAL')
    lines = ['# CSA campaign progress', '',
             'Generated by `python tools/matter/csa_campaign.py --write` from public checkpoint and later reports.',
             'Historical outcomes are inherited; this file does not turn manual or local evidence into automatic CSA PASS.', '',
             f'Latest evidence: [{latest}]({latest}). Frozen positions:862; category counts: ' +
             ', '.join(f'{key}={value}' for key, value in sorted(counts.items())) + '.',
             'Manual outcomes: ' + ', '.join(f'{key}={value}' for key, value in sorted(manual.items())) + '.', '',
             '## Initial coverage queue', '', '| Case | Endpoint | Collection | Current state |', '| --- | --- | --- | --- |']
    for group in plan['groups']:
        for row in waiting:
            if row['case'] in group['cases']:
                lines.append(f'| {row["case"]} | {row["endpoint"]} | {row["collection"]} | {row["status"]} |')
    grouped = {case for group in plan['groups'] for case in group['cases']}
    if any(row['case'] not in grouped for row in waiting):
        raise ValueError('Unplanned waiting case; update the campaign groups')
    lines.extend(['', '## Failure triage queue', '',
                  'UNTRIAGED means no new attribution is claimed. Resolve prerequisites and compare the actual failure with Core and original CSA procedure before editing native code.', '',
                  '| Case | Collection | Triage | Evidence |', '| --- | --- | --- | --- |'])
    for row in failures:
        triage = next((item for item in plan['triage'] if row['case'] in item['cases']), {})
        evidence = row.get('evidence', triage.get('evidence', 'status.md'))
        lines.append(f'| {row["case"]} | {row["collection"]} | {triage.get("kind", "UNTRIAGED")} | [{evidence}]({evidence}) |')
    lines.extend(['', '## Completion gate', '', plan['completion_gate'], '',
                  'See [execution plan](csa-campaign-plan.md) for batching, evidence, commits and resuming work.', ''])
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write', action='store_true', help='Refresh the public progress table')
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[2]
    plan, rows, counts, latest = campaign(root)
    text = render(plan, rows, counts, latest)
    path = root / 'doc/oss/csa-campaign-status.md'
    if args.write:
        with path.open('w', encoding='utf-8', newline='\n') as handle:
            handle.write(text)
    elif path.read_text(encoding='utf-8') != text:
        raise SystemExit('Stale progress table: run with --write')
    print(f'PASS campaign: {len(rows)} applicable + {counts["NA"]} NA; latest {latest}; identities, counts and progress match.')


if __name__ == '__main__':
    main()
