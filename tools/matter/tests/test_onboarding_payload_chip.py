"""CSA31 operator evidence: actual C QR bitmap, setup data and live mDNS.

Requires Pillow and zxing-cpp 2.3.0. Keep output private: it contains development
setup codes and discovery packets. The manual setup card is generated by CHIP,
not by the desktop UI. This fixture is not an official CSA result by itself.
"""
import argparse
import ctypes
import hashlib
import json
from pathlib import Path
import re
import socket
import struct
import subprocess
import time

from PIL import Image
import zxingcpp
from test_mdns_linux import decode, query


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    for name in ('payload-exe', 'qr-library', 'node', 'chip-tool', 'credentials', 'output'):
        parser.add_argument('--' + name, required=True, type=Path)
    parser.add_argument('--interface', required=True, type=int)
    args = parser.parse_args()
    out = args.output.resolve(); out.mkdir(parents=True, exist_ok=False)
    report = {'scope': __doc__, 'checks': [], 'artifacts': {}}
    for name in ('payload_exe', 'qr_library', 'node', 'chip_tool'):
        report[name + '_sha256'] = hashlib.sha256(getattr(args, name).read_bytes()).hexdigest()
    pin, discriminator, vendor, product = 20202021, 3911, 0xfff1, 0x8001

    def check(name, passed):
        report['checks'].append({'name': name, 'status': 'PASS' if passed else 'FAIL'})
        (out / 'result.json').write_text(json.dumps(report, indent=2) + '\n')
        if not passed:
            raise AssertionError(name)

    def chip(name, parameters):
        result = subprocess.run([str(args.chip_tool), *map(str, parameters)],
                                capture_output=True, text=True, timeout=20)
        text = re.sub(r'\x1b\[[0-9;]*[A-Za-z]', '', result.stdout + result.stderr)
        (out / (name + '.log')).write_text(text)
        check(name + '-exit', result.returncode == 0)
        return text

    expected = {'Version': 0, 'Discovery Bitmask': 4, 'Long discriminator': discriminator,
                'Passcode': pin, 'VendorID': vendor, 'ProductID': product, 'Custom flow': 0}
    qr = subprocess.check_output([str(args.payload_exe), *map(str, (pin, discriminator, vendor, product))], text=True).strip()
    lib = ctypes.CDLL(str(args.qr_library))
    byte_pointer = ctypes.POINTER(ctypes.c_uint8)
    lib.qrcodegen_encodeText.argtypes = [ctypes.c_char_p, byte_pointer, byte_pointer,
                                      ctypes.c_int, ctypes.c_int, ctypes.c_int, ctypes.c_int, ctypes.c_bool]
    lib.qrcodegen_encodeText.restype = ctypes.c_bool
    lib.qrcodegen_getSize.argtypes = [byte_pointer]; lib.qrcodegen_getSize.restype = ctypes.c_int
    lib.qrcodegen_getModule.argtypes = [byte_pointer, ctypes.c_int, ctypes.c_int]
    lib.qrcodegen_getModule.restype = ctypes.c_bool
    # Same version ceiling, ECC, auto mask, boost and quiet zone as Win32 build_qr.
    version, margin, scale = 4, 4, 8
    capacity = ((version * 4 + 17) ** 2 + 7) // 8 + 1
    scratch, bits = (ctypes.c_uint8 * capacity)(), (ctypes.c_uint8 * capacity)()
    check('C-QR-matrix-encoded', lib.qrcodegen_encodeText(qr.encode(), scratch, bits, 1, 1, version, -1, True))
    size = lib.qrcodegen_getSize(bits)
    image = Image.new('L', ((size + margin * 2) * scale,) * 2, 255)
    for y in range(size):
        for x in range(size):
            if lib.qrcodegen_getModule(bits, x, y):
                left, top = (x + margin) * scale, (y + margin) * scale
                image.paste(0, (left, top, left + scale, top + scale))
    image.save(out / 'qr.png')
    decoded = zxingcpp.read_barcode(image)
    check('independent-optical-scan', decoded is not None and decoded.text == qr)
    check('blank-image-rejected', zxingcpp.read_barcode(Image.new('L', image.size, 255)) is None)
    parsed = chip('parse-scanned-QR', ['payload', 'parse-setup-payload', decoded.text])
    for field, value in expected.items():
        match = re.search(r'\[SPL\]\s+' + re.escape(field) + r':\s*(0x[\da-fA-F]+|\d+)', parsed)
        check('parsed-' + field, bool(match) and int(match[1], 16 if field == 'Discovery Bitmask' else 10) == value)
    generated = chip('reference-QR', ['payload', 'generate-qrcode', '--setup-pin-code', pin,
                     '--discriminator', discriminator, '--rendezvous', 4, '--vendor-id', vendor, '--product-id', product])
    check('C-payload-matches-CHIP', qr == re.search(r'QR Code: (MT:[A-Z0-9.\-]+)', generated)[1])
    manual_log = chip('reference-manual', ['payload', 'generate-manualcode', '--setup-pin-code', pin,
                      '--discriminator', discriminator, '--version', 0, '--vendor-id', vendor, '--product-id', product])
    manual = re.search(r'Manual Code:\s*(\d+)', manual_log)[1]
    check('standard-manual-eleven-digits', len(manual) == 11)
    manual_parsed = chip('parse-manual', ['payload', 'parse-setup-payload', manual])
    for field, value in [('Short discriminator', discriminator >> 8), ('Passcode', pin)]:
        match = re.search(re.escape(field) + r':\s*(\d+)', manual_parsed)
        check('manual-' + field, bool(match) and int(match[1]) == value)
    invalid = manual[:-1] + str((int(manual[-1]) + 1) % 10)
    negative = subprocess.run([str(args.chip_tool), 'payload', 'parse-setup-payload', invalid], capture_output=True, text=True, timeout=20)
    (out / 'invalid-manual.log').write_text(negative.stdout + negative.stderr)
    check('bad-manual-checksum-rejected', negative.returncode != 0)

    with socket.socket(socket.AF_INET6, socket.SOCK_DGRAM) as sock, \
            (out / 'node.log').open('w') as log, (out / 'node.err').open('w') as err:
        sock.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
        sock.setsockopt(socket.IPPROTO_IPV6, socket.IPV6_V6ONLY, 1)
        sock.setsockopt(socket.IPPROTO_IPV6, socket.IPV6_MULTICAST_IF, args.interface)
        sock.setsockopt(socket.IPPROTO_IPV6, socket.IPV6_MULTICAST_HOPS, 255)
        sock.bind(('::', 5353))
        sock.setsockopt(socket.IPPROTO_IPV6, socket.IPV6_JOIN_GROUP,
                        socket.inet_pton(socket.AF_INET6, 'ff02::fb') + struct.pack('@I', args.interface))
        sock.settimeout(.25)
        node = subprocess.Popen([str(args.node), '--interface', str(args.interface), '--seconds', '90',
                                 '--port', '5583', '--discriminator', str(discriminator), '--pin', str(pin),
                                 '--credentials', str(args.credentials), '--state', str(out / 'state.tlv'),
                                 '--three-phase', '--source-registers', '--meter-services', '--wifi-sim-connected'], stdout=log, stderr=err)
        try:
            deadline = time.monotonic() + 15
            while time.monotonic() < deadline:
                text = (out / 'node.log').read_text()
                if 'PUBLISHED' in text or node.poll() is not None:
                    break
                time.sleep(.05)
            check('node-published', node.poll() is None and 'PUBLISHED' in text)
            instance, service = re.search(r'NODE instance=(\S+) service=(\S+)', text).groups()
            owner = (instance + '.' + service).lower(); observed = None
            deadline = time.monotonic() + 8
            while time.monotonic() < deadline and observed is None:
                sock.sendto(query(owner, 16), ('ff02::fb', 5353, 0, args.interface))
                try:
                    packet, _ = sock.recvfrom(8192)
                except socket.timeout:
                    continue
                flags, records = decode(packet)
                for name, kind, _, ttl, payload in records:
                    if flags & 0x8000 and name == owner and kind == 16 and ttl:
                        fields = {}; at = 0
                        while at < len(payload):
                            length = payload[at]; at += 1
                            key, value = payload[at:at + length].split(b'=', 1); at += length
                            fields[key.decode()] = value.decode()
                        observed = fields; (out / 'advertisement.bin').write_bytes(packet)
            check('advertised-discriminator-matches-scanned-QR', observed is not None and observed.get('D') == str(discriminator))
            check('advertised-basic-window-open', observed.get('CM') == '1')
            (out / 'setup.json').write_text(json.dumps({'qr': qr, 'manual': manual, 'advertised': observed,
                'manual_source': 'CHIP-generated laboratory setup card, not a native GUI field',
                'pin': pin, 'discriminator': discriminator, 'vendor': vendor, 'product': product}, indent=2))
        finally:
            if node.poll() is None:
                node.terminate()
            check('node-clean-stop', node.wait(timeout=20) == 0)
    check('node-stderr-empty', not (out / 'node.err').read_bytes())
    for name in ['qr.png', 'setup.json', 'advertisement.bin']:
        report['artifacts'][name] = hashlib.sha256((out / name).read_bytes()).hexdigest()
    report['result'] = 'PASS'
    (out / 'result.json').write_text(json.dumps(report, indent=2) + '\n')
    print('PASS onboarding operator evidence:', len(report['checks']), 'checks')


if __name__ == '__main__':
    main()
