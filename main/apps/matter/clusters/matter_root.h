/* Attribute model for Core 1.6.1: ep0 Descriptor rev3, Basic Information rev6.
 * Base constructor has these two servers and empty ClientList/PartsList; owner
 * registrations below extend them. Root Node type
 * 0x16/rev5 describes the target simulation, NOT complete device conformance.
 * Base constructor registers StartUp; owner emits it with matter_root_startup.
 * It has no commissioning;
 * optional attachments below provide GC/Wi-Fi/credentials and CASE Complete.
 */
typedef struct { size_t size; uint8_t data[64]; } Matter_Root_Text_T;
typedef struct {
    size_t node_label_size;
    uint8_t node_label[32], location[2];
} Matter_Root_Settings_T;
typedef struct {
    uint16_t case_sessions, subscriptions, invokes, writes, read_paths, subscribe_paths;
} Matter_Root_Capabilities_T;
typedef struct {
    Matter_Root_Text_T vendor_name, product_name, hardware_string, software_string, unique_id;
    uint16_t vendor_id, product_id, hardware_version;
    uint32_t software_version, configuration_version;
    Matter_Root_Capabilities_T capabilities;
    Matter_Root_Settings_T settings;
    /* Core 7.10.3: application supplies independently randomized initial values
     * on each publication. Tests may use deterministic seeds. Not persistent
     * ConfigurationVersion, which must be >=1 and increase on config changes. */
    uint32_t descriptor_version, basic_version;
} Matter_Root_Config_T;
typedef struct {
    void* user;
    /* Fills owned storage, no borrowed string pointers. Called once by new.
     * Read durable identity/settings; invalid config or failure aborts new.
     * UniqueID <=32 UTF8 bytes, regenerated by application on factory reset,
     * distinct from serial/persistent IDs. No generation of production IDs here.
     * CapabilityMinima must describe the application composition's resource
     * guarantees; Root encodes these values but does not provision its pools. */
    Matter_Result_T (*load)(void*, Matter_Root_Config_T*);
    /* Authenticated session/grant policy belongs to application on EVERY call.
     * Return SUCCESS/UNSUPPORTED_ACCESS/ACCESS_RESTRICTED. No allow-all default. */
    uint8_t (*authorize)(void*, Matter_Exchange_Session_T, const Matter_Im_Path_T*, Matter_Im_Privilege_T);
    /* Atomic durable commit of the complete pair, before publication/version.
     * Failure MUST leave backend unchanged. No retained pointer or reentry.
     * Bounded synchronous/nonblocking; future slow storage needs a separate
     * async integration, not waiting inside IM. Unknown Location codes must
     * result in region-agnostic hardware policy (Core 11.1.5.7). */
    Matter_Result_T (*store)(void*, const Matter_Root_Settings_T*);
} Matter_Root_Port_T;
typedef struct Matter_Root* Matter_Root_T;

/* Heap-owned config/TLV scratch plus owned Descriptor/Basic cluster registries.
 * GC constructor adds one registry. Copied port with borrowed user.
 * Independent instances, single owner thread, no tasks/globals/hardware.
 * Serialize all callbacks for the entire IM process call. Returned IM ports
 * borrow root; destroy all handlers/bindings before delete. Only Write mutates
 * settings; direct callbacks are not a substitute for IM access/schema checks.
 * Sizes are UTF8 bytes, embedded NUL allowed. Location normalized to uppercase.
 * DataVersion wraps uint32 and increments only on a changed successful store;
 * no-op writes do not store. ConfigurationVersion is NOT changed by NodeLabel.
 */
Matter_Root_T matter_root_new(const Matter_Root_Port_T*);
/* Owner-thread copy of the immutable, advertised composition budget. */
Matter_Result_T matter_root_capabilities(Matter_Root_T,Matter_Root_Capabilities_T*);
/* Once per node boot, before other Data Model producers. Retry on error; repeat
 * success is a no-op. No event at mere construction or service restart. */
Matter_Result_T matter_root_startup(Matter_Root_T,Matter_Events_T,uint64_t timestamp_ms);
Matter_Result_T matter_root_ports(Matter_Root_T, Matter_Im_Read_Port_T*, Matter_Im_Write_Port_T*);
Matter_Result_T matter_root_delete(Matter_Root_T);
/* Register an implemented client role on an existing endpoint; bounded to eight
 * IDs, idempotent. Owner only, before serving IM; increments Descriptor version. */
Matter_Result_T matter_root_add_client(Matter_Root_T,uint16_t endpoint,uint32_t cluster);
/* Add an implemented utility type to EP0, preserving Root Node/rev5.
 * At most four additional types, idempotent for the same revision; configure
 * before publication. Caller verifies the device's required cluster roles. */
Matter_Result_T matter_root_add_device_type(Matter_Root_T,uint32_t type,uint16_t revision);
/* Query the same device types exposed by Descriptor, for ACL target matching. */
bool matter_root_has_device_type(Matter_Root_T,uint16_t endpoint,uint32_t type);
/* Generic ep0 servers. Borrowed and pinned through Root deletion; attach before
 * topology publication. Same Read/Write/Invoke adapters and application ACL.
 * Cluster IDs cannot shadow built-in servers. Up to 16 custom attachments plus
 * nine built-in servers. root_cluster returns a borrowed common handle;
 * Root owns Descriptor/Basic/GC and pins every externally attached cluster. */
Matter_Result_T matter_root_attach_cluster(Matter_Root_T,Matter_Cluster_T);
Matter_Cluster_T matter_root_cluster(Matter_Root_T,uint32_t);
/* Optional endpoints; constructor creates EP0, old attach/lookup use EP0.
 * The existing IM ports route all configured endpoints.
 * Up to 8 endpoints, each initially with one configured device type, an owned
 * Descriptor rev3, empty ClientList/PartsList and up to 15 other servers.
 * add_endpoint preserves the untagged leaf default; the additive APIs below
 * configure tags, composition and additional device types before publication.
 * IDs 1..65534, revision >=1; config is copied. Allocation failure is atomic.
 * Add/attach ONLY before publishing topology/creating handlers, while GC idle.
 * Root owns leaf contexts/Descriptors and pins externally owned clusters.
 * Delete handlers before Root; additional pins on owned Descriptors block delete.
 * Application supplies independent randomized initial DataVersions. This
 * config declares a target device type, not proof of its complete conformance.
 */
typedef struct {
    uint16_t endpoint,revision; uint32_t device_type,data_version;
} Matter_Root_Endpoint_Config_T;
Matter_Result_T matter_root_add_endpoint(Matter_Root_T,const Matter_Root_Endpoint_Config_T*);
/* Configure composition before serving IM. parent=0 means a direct Root child.
 * Endpoints must exist; cycles and self-parenting are rejected. Root PartsList
 * always contains all endpoints; other PartsLists contain direct children.
 * Additional device types are copied, at most four per endpoint. */
Matter_Result_T matter_root_set_parent(Matter_Root_T,uint16_t endpoint,uint16_t parent);
Matter_Result_T matter_root_add_device_type_at(Matter_Root_T,uint16_t endpoint,uint32_t type,uint16_t revision);
/* Standard semantic tags (MfgCode=null, Label omitted). Copied at construction;
 * 1..6 distinct namespace/tag pairs; count=0 preserves the untagged default.
 * Same ownership as add_endpoint. */
typedef struct { uint8_t namespace_id,tag; } Matter_Root_Tag_T;
Matter_Result_T matter_root_add_tagged_endpoint(Matter_Root_T,const Matter_Root_Endpoint_Config_T*,const Matter_Root_Tag_T*,size_t count);
Matter_Result_T matter_root_attach_cluster_at(Matter_Root_T,uint16_t endpoint,Matter_Cluster_T);
/* Borrowed lookup, including EP0; old root_cluster remains the EP0 shorthand. */
Matter_Cluster_T matter_root_cluster_at(Matter_Root_T,uint16_t endpoint,uint32_t cluster);

/* Optional General Commissioning rev2, no TC/NR, powered device.
 * Old constructor/ports retain their two-cluster behavior. Complete after
 * AddNOC requires the optional completion backend and CASE Invoke binding.
 */
typedef struct {
    uint16_t recommended_seconds, cumulative_seconds;
    uint8_t regulatory_config, location_capability;
    bool concurrent_connection, recover_pending;
    uint32_t data_version; /* Random initial value supplied by application. */
} Matter_Root_Commissioning_Config_T;
typedef struct {
    void* user;
    /* Atomic creation of recovery marker and snapshots of network/credentials.
     * Called once on first arm, not rearm. Failure must have no effects. */
    Matter_Result_T (*begin)(void*);
    /* Idempotent, bounded progress through Core 11.10.7.2.2 cleanup: retire ALL
     * PASE sessions/drain, revoke grants, restore network/credential snapshots,
     * remove temporary keys/roots, then clear recovery marker. OK only when done;
     * PENDING for drain, error leaves cleanup blocked and retryable. Never
     * destroy root or handlers inline. No optional non-fabric rollback here. */
    Matter_Result_T (*cleanup)(void*);
    /* Atomic durable Location + supplied RegulatoryConfig/radio update.
     * candidate already honors LocationCapability. On OK always commit Location,
     * even if country_supported=false (ValueOutsideRange); use region-agnostic
     * radio settings for unsupported countries. Error leaves everything intact.
     * No callback may retain input pointers, reenter or block. */
    Matter_Result_T (*regulatory)(void*, const Matter_Root_Settings_T*, uint8_t candidate, bool* country_supported);
    /* Current admission window (initial/basic/enhanced), sampled before CASE
     * first-arm. Optional only for owners with no commissioning window. Errors
     * fail closed; callback must not reenter Root. Core 11.10.7.2. */
    Matter_Result_T (*window_open)(void*, bool* open);
} Matter_Root_Commissioning_Port_T;
typedef enum { MATTER_ROOT_FAIL_SAFE_IDLE, MATTER_ROOT_FAIL_SAFE_ARMED, MATTER_ROOT_FAIL_SAFE_CLEANUP } Matter_Root_Fail_Safe_State_T;
/* Caller owns one small binding per Invoke handler, alive until its deletion.
 * Session must be authenticated PASE, never a client-supplied identity; fabric
 * association after AddNOC is resolved by matter_root_invoke_fabric. Required to prevent concurrent handlers sharing cached auth state. */
typedef struct { Matter_Root_T root; Matter_Exchange_Session_T session; } Matter_Root_Invoke_Binding_T;
Matter_Root_T matter_root_new_commissioning(const Matter_Root_Port_T*,
    const Matter_Root_Commissioning_Config_T*, const Matter_Root_Commissioning_Port_T*, uint64_t now_ms);
Matter_Result_T matter_root_invoke_port(Matter_Root_T, Matter_Exchange_Session_T,
    Matter_Root_Invoke_Binding_T*, Matter_Im_Invoke_Port_T*);
/* Owner MUST process current monotonic time BEFORE IM processing and service
 * deadline even when no network traffic arrives. Expiry disarms immediately;
 * cleanup is performed only here, never inside an Invoke callback. Zero arm
 * queues cleanup, so the PASE reply may be lost when its session is retired.
 * Delete refuses an armed/cleaning model: expire, process/drain, then delete.
 * recover_pending requests the same cleanup after a restart BEFORE admission.
 */
Matter_Result_T matter_root_process(Matter_Root_T, uint64_t now_ms);
Matter_Result_T matter_root_deadline(Matter_Root_T, uint64_t* deadline_ms);
Matter_Result_T matter_root_expire(Matter_Root_T);
Matter_Result_T matter_root_fail_safe_state(Matter_Root_T, Matter_Root_Fail_Safe_State_T*);
/* Authenticated PASE handoff only: arm the initial 60s fail-safe and journal
 * before exposing the session to IM. Refuse an already armed/cleaning context;
 * a failed begin leaves it idle. Roots without GC are unaffected. */
Matter_Result_T matter_root_pase_established(Matter_Root_T, uint64_t now_ms);
/* Optional Wi-Fi model, borrowed until Root and all its handlers are destroyed.
 * Attach ONCE before publishing topology, to an idle concurrent GC instance.
 * Application GC begin/cleanup MUST checkpoint/rollback this SAME Wi-Fi model;
 * cleanup retires PASE/drains first, rolls back Wi-Fi, clears journal last.
 * No non-concurrent commissioning channel handover in this host subset.
 */
Matter_Result_T matter_root_attach_wifi(Matter_Root_T, Matter_Wifi_T);
Matter_Result_T matter_root_wifi_invoke_port(Matter_Root_T, Matter_Exchange_Session_T,
    Matter_Root_Invoke_Binding_T*, Matter_Im_Invoke_Port_T*, Matter_Im_Invoke_Async_Port_T*);
/* Optional pre-AddNOC Operational Credentials. Attach before topology publication.
 * GC cleanup must revoke/drain PASE, rollback opcreds, then clear its journal.
 * All handlers and Root borrow the module; destroy them before module deletion. */
Matter_Result_T matter_root_attach_opcreds(Matter_Root_T, Matter_Opcreds_T);
/* Optional ACL model, borrowed through Root/handler deletion. Attach once before
 * publishing topology. Application authorizer uses this SAME model's policy. */
Matter_Result_T matter_root_attach_acl(Matter_Root_T,Matter_Acl_T);
/* Optional rev4 Group Key Management, borrowed through Root/handler deletion.
 * Same fabric image as AddNOC/CASE; attach before publishing topology. */
Matter_Result_T matter_root_attach_groupkey(Matter_Root_T,Matter_Groupkey_T);
/* Both diagnostic models borrowed through Root/handler deletion. Attach before
 * topology publication; application refreshes the model BEFORE IM processing. */
Matter_Result_T matter_root_attach_diagnostics(Matter_Root_T,Matter_Diagnostics_T);
