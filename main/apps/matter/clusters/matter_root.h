/* Optional completion backend. Owner serializes transaction participants.
 * complete is pumped by root_process while fail-safe remains armed. Root
 * rechecks its application authorizer on the original CASE token before each call. It MUST
 * close commissioning admission, revoke/drain ALL PASE, then atomically commit
 * network/credentials/fabrics and clear recovery journal LAST. PENDING keeps
 * rollback possible; error MUST NOT leave a partial commit. No blocking/reentry.
 * An IM cancellation detaches the attempt; already committed effects remain.
 * Cleanup must also retire CASE sessions on fabrics being rolled back. */
typedef struct { void* user; Matter_Result_T (*complete)(void*,uint8_t fabric_index); } Matter_Root_Complete_Port_T;
